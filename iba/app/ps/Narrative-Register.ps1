<#
.SYNOPSIS
    The narrative claim register in iba.db (escalation #2110): add and edit claims, link them to
    the blocks that tell them, search, show a claim's history, check the chapters against the
    database, and publish the three register files. Every action dispatches through run.py, work
    package narrative-register.

.DESCRIPTION
    A claim is a statement derived from sources that goes beyond their mere text, in its own
    wording. The narrative is the story, held in iba.db as blocks (a heading and its text); a
    claim is told by a block (#2172). The narrative is written through Strand-Reading.ps1 -Step
    Rewrite, which publishes each chapter file from the database; a chapter file is an export.
    Every change keeps its before and after (history triggers on the tables). The published files
    are regenerated by -Action Export; an edit made only in a published file is not kept.

    Write actions (need -By Claude|Researcher):
      AddClaim     -Text "<claim>" [-BeyondText ..] [-Source "Rom 7:15-21; lexical: kāʿas (anger)"]
                   [-Origin narrative|"original essay"] [-Verdict ..] [-IRead 1] [-MainChapter 10.1]
                   [-MainSection "<heading>"] [-ClaimRef K-2] [-Note ..]
      Edit         -Claim C-412 [-Text ..] [-BeyondText ..] [-Verdict ..] [-Status ..] [-IRead 0|1]
                   [-Source ..(added)] [-Note ..]
      Tell         -Claim C-412 -Chapter 10.1 -Section "<heading>|<Parent > Heading>" [-Kind "in full"|"in part"|pointer]
                   [-Part "<which part>"] [-Note ..]
      Untell       -Claim C-412 -Chapter 10.1 -Section "<heading>|<Parent > Heading>" [-Note ..]
      Withdraw     -Claim C-412 [-Note ..]
      EditNote     -Heading "<block heading>" [-Text ..] [-NewHeading ..] [-Ordinal n]
      AddChapter   -Chapter 10.16 -Title ".." -Kind "key characteristic" -Purpose ".." -PurposeRef "#nnnn"
                   (-After 10.15 | -ReadingOrder n) [-CurrentFile <file on disk>] [-State draft]
                   [-BuiltFrom ..] [-FileStem ..] [-Note "<reason>"]
                   (the chapter table is the authority for the chapters, #2155: later chapters move
                   down, section rows come from the file, a Structure log entry is written; -Kind is
                   cfg_enum narrative_chapter_kind; a file is needed unless the kind is in
                   narrative.chapter_kinds_without_file)
      EditChapter  -Chapter 10.1 [-NewNumber ..] [-Title ..] [-Kind ..] [-Purpose ..] [-PurposeRef ..]
                   [-State ..] [-CurrentFile ..] [-CurrentVersion n] [-After <chapter> | -ReadingOrder n]
                   [-Inactive 0|1] [-Note "<reason>"]   (a structural change is logged)
      EditSection  -Chapter 10.1 -Section "<heading>" [-NewHeading ..] [-Level n] [-Ordinal n]
                   [-LastVersion n]   (an unknown -Section with -Level adds it)
    Read-only:
      Find         any of -Verse -Chapter [-Section] -Claim -Text -Escalation -Thread -Verdict
                   -NotInNarrative -ToldInMoreThanOne (combined with AND)
      History      -Claim C-412
      Check
      Export
      QuoteCheck   -File <chapter.md> [-Against <previous version.md>]   (#2173 G14: every quotation,
                   or only those in lines added against -Against, must be in the ESV text;
                   lib/quotecheck.py; session-close SC5 runs it on every chapter changed)

.EXAMPLE
    iba\app\ps\Narrative-Register.ps1 -Action Find -Verse "1 Samuel 24:5"
.EXAMPLE
    iba\app\ps\Narrative-Register.ps1 -Action Tell -Claim K10 -Chapter 8 -Section "The bosom" -Kind "in part" -Part "anger lodges in the bosom" -By Claude
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('AddClaim', 'Edit', 'Tell', 'Untell', 'Withdraw', 'EditNote', 'AddChapter', 'EditChapter',
                 'EditSection', 'Find', 'History', 'Check', 'Export', 'QuoteCheck')]
    [string] $Action,
    [ValidateSet('Claude', 'Researcher')] [string] $By,
    [string] $Claim, [string] $ClaimRef, [string] $Text, [string] $BeyondText, [string] $Source,
    [string] $Origin, [string] $Verdict, [string] $Status, [string] $IRead,
    [string] $MainChapter, [string] $MainSection,
    [string] $Chapter, [string] $Section, [string] $Kind, [string] $Part,
    [string] $Heading, [string] $NewHeading, [string] $Ordinal, [string] $Level, [string] $LastVersion,
    [string] $NewNumber, [string] $Title, [string] $State, [string] $CurrentFile, [string] $CurrentVersion,
    [string] $ReadingOrder, [string] $Inactive,
    [string] $Purpose, [string] $PurposeRef, [string] $After, [string] $BuiltFrom, [string] $FileStem,
    [string] $File, [string] $Note, [string] $Against,
    [string] $Verse, [string] $Escalation, [string] $Thread,
    [switch] $NotInNarrative, [switch] $ToldInMoreThanOne,
    [switch] $Trace
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$env:PYTHONUTF8 = '1'
if ($Trace) { $env:IBA_TRACE = '1' }

$RepoRoot = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSScriptRoot))
Set-Location $RepoRoot
. $PSScriptRoot\_lib\Notify.ps1

$stepName = @{
    AddClaim = 'add_claim'; Edit = 'edit'; Tell = 'tell'; Untell = 'untell'; Withdraw = 'withdraw'
    EditNote = 'edit_note'; AddChapter = 'add_chapter'; EditChapter = 'edit_chapter'; EditSection = 'edit_section'
    Find = 'find'; History = 'history'; Check = 'check'; Export = 'export'
    QuoteCheck = 'quote_check'
}[$Action]
$stepId = "narrative_register.$stepName"
$runId = "RUN-$(Get-Date -Format 'yyyyMMdd_HHmmss_fff')-NARRATIVEREG"

$paramArgs = @()
foreach ($name in @('By', 'Claim', 'ClaimRef', 'Text', 'BeyondText', 'Source', 'Origin', 'Verdict',
                    'Status', 'IRead', 'MainChapter', 'MainSection', 'Chapter', 'Section',
                    'Kind', 'Part', 'Heading', 'NewHeading', 'Ordinal', 'Level', 'LastVersion',
                    'NewNumber', 'Title', 'State', 'CurrentFile', 'CurrentVersion', 'ReadingOrder',
                    'Inactive', 'Purpose', 'PurposeRef', 'After', 'BuiltFrom', 'FileStem',
                    'File', 'Note', 'Against', 'Verse', 'Escalation', 'Thread')) {
    $value = Get-Variable -Name $name -ValueOnly
    if ($PSBoundParameters.ContainsKey($name)) { $paramArgs += @('--param', "$name=$value") }
}
if ($NotInNarrative) { $paramArgs += @('--param', 'NotInNarrative=1') }
if ($ToldInMoreThanOne) { $paramArgs += @('--param', 'ToldInMoreThanOne=1') }

Write-IbaRunHeader -WorkPackage 'narrative-register' -Step $stepId -RunId $runId
$json = python -m iba.app.run narrative-register --step $stepId --run-id $runId @paramArgs
$code = $LASTEXITCODE
$res = $json | ConvertFrom-Json
Write-IbaStepResult -Step $stepId -Path $res.path -Message $res.message -Code $code
exit $code
