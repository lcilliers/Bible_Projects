"""surface_maps_2361_v1_20261106.py -- escalation #2361, stage 6: the two generated sections of the config report and the retirement of the earlier file route.

  cfg_report_section  16 surface_cycle_map ("The surface cycle") and 17 ai_use_map ("The AI use map") of configmaint.report, generated by
                      lib/surfacecyclemap.py from the registers at the moment the report is made
  cfg_utility         surfacecyclemap (config_exempt: it reads through the report's own query function)
  retired             the file route of the AI base: steps surface_base.status and surface_base.run (inactive; the table route is surface_base.ask), and the
                      settings that only that route read -- surface_judge.base_input_suffix (the input file name) and surface_judge.base_prompt (the prompt
                      text, now the cfg_ai_prompt key base.word) -- are set inactive. surface_judge.word_prompt stays while Surface-Judge.ps1 still reads it
All cfg_* writes through configmaint.apply_logged(). A named rollback snapshot is taken before a live apply. Idempotent. One transaction.

Usage:
    python iba/app/migration/surface_maps_2361_v1_20261106.py [--db PATH] [--dry-run] [--no-snapshot]
"""
import argparse
import pathlib
import sys

ROOT = next(p for p in pathlib.Path(__file__).resolve().parents if (p / "iba" / "app").is_dir())  # live or archived
sys.path.insert(0, str(ROOT))
from iba.app.handlers.configmaint import apply_logged  # noqa: E402
from iba.app.lib.cfg import Cfg  # noqa: E402

DEFAULT_DB = pathlib.Path(r"C:\Bible_study_projects\iba\app\db\iba.db")
RUN_ID = "DEVMODE-2361-SURFACE-MAPS-20261106"
MODULE = "surface_maps_2361_v1_20261106"
STEP = "configmaint.report"
SECTIONS = [
    (16, "surface_cycle_map", "## 16. The surface cycle - modules, steps, tables and settings (generated)", "16. The surface cycle"),
    (17, "ai_use_map", "## 17. The AI use map - models, prompts and calls (generated)", "17. The AI use map"),
]
RETIRE_STEPS = ["surface_base.status", "surface_base.run"]
RETIRE_SETTINGS = ["surface_judge.base_input_suffix", "surface_judge.base_prompt"]
UTILITIES = [
    ("surfacecyclemap", "iba/app/lib/surfacecyclemap.py", 0, "surfacecyclemap.py -- the generated sections 16 (the surface cycle) and 17 (the AI use map) of the config report, built from "
     "the registers (escalation #2361).", 1, "reads through the config report's own query function, not Cfg"),
    (MODULE, f"iba/app/migration/archive/{MODULE}.py", 1, f"ONE-OFF migration -- escalation #2361 stage 6: the generated cycle and AI use sections of the config report and the "
     f"retirement of the file route of the AI base; run_id {RUN_ID}.", 1, "one-off migration script -- writes cfg_* rows through configmaint.apply_logged, same class as the other Developer Mode migrations"),
]


UTIL_TEXT = {
    "surfacebase": "surfacebase.py -- the shape of an AI base answer (a known relation, a base of the configured pattern): the check used by Surface-Base.ps1 -Action Ask (escalation #2359, #2361).",
    "handlers_surfacebase": "handlers/surfacebase.py -- the run.py handler for work package surface-base: Ask, the AI base through the AI client (Surface-Base.ps1, escalation #2361).",
}


def plan(conn):
    ops = []
    has = lambda sql, *a: conn.execute(sql, a).fetchone() is not None  # noqa: E731
    for ordinal, key, heading, toc in SECTIONS:
        if not has("SELECT 1 FROM cfg_report_section WHERE step=? AND section_key=?", STEP, key):
            ops.append(("cfg_report_section", "insert", {}, {"step": STEP, "ordinal": ordinal, "section_key": key, "heading": heading, "toc_label": toc, "include": 1, "inactive": 0}))
    for step in RETIRE_STEPS:
        if has("SELECT 1 FROM cfg_step WHERE step=? AND inactive=0", step):
            ops.append(("cfg_step", "update", {"step": step}, {"inactive": 1}))
    for key in RETIRE_SETTINGS:
        if has("SELECT 1 FROM cfg_setting WHERE key=? AND inactive=0", key):
            ops.append(("cfg_setting", "update", {"key": key}, {"inactive": 1}))
    for module, text in UTIL_TEXT.items():
        row = conn.execute("SELECT purpose FROM cfg_utility WHERE module=?", (module,)).fetchone()
        if row is not None and row[0] != text:
            ops.append(("cfg_utility", "update", {"module": module}, {"purpose": text}))
    for module, path, inactive, purpose, exempt, reason in UTILITIES:
        if not has("SELECT 1 FROM cfg_utility WHERE module=?", module):
            ops.append(("cfg_utility", "insert", {}, {"module": module, "file_path": path, "purpose": purpose, "inactive": inactive, "config_exempt": exempt,
                                                      "config_exempt_reason": reason, "crash_escalation_reviewed": 0, "crash_escalation_note": None}))
    return ops


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(DEFAULT_DB))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-snapshot", action="store_true", help="for a test copy: no rollback snapshot")
    a = ap.parse_args()
    cfg = Cfg(pathlib.Path(a.db))
    conn = cfg.conn
    ops = plan(conn)
    if a.dry_run:
        print(f"DRY RUN: {len(ops)} cfg write(s)")
        return 0
    if not ops:
        print("already applied: nothing changed")
        return 0
    if not a.no_snapshot:
        from iba.app.lib import dbsnapshot
        print(f"named rollback snapshot: {dbsnapshot.snapshot('pre-2361-maps', named=True)}")
    try:
        conn.execute("SAVEPOINT surface_maps")
        for t, op, where, set_ in ops:
            apply_logged(conn, RUN_ID, t, op, where, set_)
        conn.execute("RELEASE surface_maps")
        conn.commit()
    except Exception:
        conn.execute("ROLLBACK TO surface_maps")
        conn.execute("RELEASE surface_maps")
        raise
    print(f"applied (run {RUN_ID}): {len(ops)} cfg write(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
