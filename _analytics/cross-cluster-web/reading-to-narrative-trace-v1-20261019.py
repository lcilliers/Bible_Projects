"""Reading-to-narrative trace (v1, 2026-10-19). Read-only against iba.db.

Researcher, chat 2026-10-19 (verbatim): "yesterday we did substantial work around the flesh and body,
including adding new verses for body but I only see limited edits in the narrative related to body.
I have no easy way to check if all the analysis that you showed me in the md files actually found its
way into the narratives".

For each reading file given (a .md reading, or a .csv with a `reference` column), it lists every verse
the file names and, for each, where the current narrative tells it (current `narrative_citation` rows in
active chapters, with the section), and whether it is a claim source. It also says whether the file is
named in any register update (`narrative_update.source_files`), i.e. whether a weave was recorded from it.
Verse references are read with the register's own parser (`narrativeregister.parse_refs`), so they are
read exactly as the chapters are.

A verse a reading names but the narrative does not tell is NOT automatically a gap: readings quote
neighbouring verses for context. The list of untold verses is what to check by hand.

Usage:
  python reading-to-narrative-trace-v1-20261019.py <out-name> <file> [<file> ...]
Writes <out-name>.md and <out-name>.csv next to this script.
"""
import csv, json, pathlib, re, sqlite3, sys
from collections import defaultdict

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
from iba.app.lib.narrativeregister import VerseIndex, parse_refs  # noqa: E402

sys.stdout.reconfigure(encoding='utf-8')
DB = ROOT / 'iba/app/db/iba.db'


class ReadOnlyCfg:
    """The two things VerseIndex needs (a connection and cfg_setting), on a read-only connection."""
    def __init__(self):
        self.conn = sqlite3.connect(f'file:{DB}?mode=ro', uri=True)
        self.conn.row_factory = sqlite3.Row

    def setting(self, key, default=None):
        r = self.conn.execute("SELECT value FROM cfg_setting WHERE key=? AND inactive=0", (key,)).fetchone()
        return json.loads(r['value']) if r else default


cfg = ReadOnlyCfg()
c = cfg.conn
vx = VerseIndex(cfg)
ref_of = {vid: ref for ref, vid in ((r['reference'], r['id']) for r in c.execute('SELECT id, reference FROM verse WHERE deleted=0'))}
told = defaultdict(set)
for vid, chno, head in c.execute("""SELECT nc.verse_id, ch.chapter_no, ns.heading FROM narrative_citation nc
    JOIN narrative_chapter ch ON ch.id = nc.chapter_id AND ch.inactive = 0
    LEFT JOIN narrative_section ns ON ns.id = nc.section_id
    WHERE nc.last_version IS NULL AND nc.verse_id IS NOT NULL"""):
    told[vid].add(f'{chno} {head or ""}'.strip())
claims = defaultdict(set)
for vid, ref in c.execute("""SELECT s.verse_id, cl.claim_ref FROM narrative_claim_source s JOIN narrative_claim cl ON cl.id = s.claim_id
    WHERE s.verse_id IS NOT NULL AND cl.status = 'current'"""):
    claims[vid].add(ref)
updates = [(r['id'], r['update_date'], r['title'], r['source_files'] or '') for r in
           c.execute('SELECT id, update_date, title, source_files FROM narrative_update')]
by_ref = {}
for vid, ref in ref_of.items(): by_ref[ref] = vid


def verses_in(path: pathlib.Path):
    if path.suffix.lower() == '.csv':
        out = []
        for r in csv.DictReader(open(path, encoding='utf-8-sig')):
            ref = (r.get('reference') or '').strip()
            if ref in by_ref: out.append(by_ref[ref])
            else:
                out += [x.verse_id for x in parse_refs(ref, vx) if x.verse_id]
        return out
    text = path.read_text(encoding='utf-8')
    return [x.verse_id for x in parse_refs(text, vx) if x.verse_id]


name = sys.argv[1]
files = [pathlib.Path(a) for a in sys.argv[2:]]
rows, summary = [], []
for f in files:
    vids = list(dict.fromkeys(verses_in(f)))
    rel = f.resolve().relative_to(ROOT).as_posix()
    ups = [f'{u[0]} ({u[1]})' for u in updates if rel in u[3] or f.name in u[3]]
    n_told = sum(1 for v in vids if told.get(v))
    summary.append((rel, len(vids), n_told, len(vids) - n_told, sum(1 for v in vids if claims.get(v)), ups))
    for v in vids:
        rows.append([rel, ref_of.get(v), 'yes' if told.get(v) else 'no', ' | '.join(sorted(told.get(v, ()))),
                     ' '.join(sorted(claims.get(v, ())))])

with open(HERE / f'{name}.csv', 'w', newline='', encoding='utf-8') as fh:
    w = csv.writer(fh); w.writerow(['file', 'verse', 'told_in_narrative', 'where_told', 'claim_sources']); w.writerows(rows)
lines = [f'# Reading-to-narrative trace: {name}', '',
         'Generated by `reading-to-narrative-trace-v1-20261019.py` (read-only). Per file: the verses it names, how many the '
         'current narrative tells, and the register updates that name the file. Verse-level detail: '
         f'[`{name}.csv`]({name}.csv).', '',
         '| File | Verses named | Told now | Not told | Claim sources | Register updates naming the file |',
         '| --- | --- | --- | --- | --- | --- |']
for rel, n, t, u, cl, ups in summary:
    lines.append(f'| `{rel}` | {n} | {t} | {u} | {cl} | {", ".join(ups) or "none"} |')
lines += ['', '## Verses named but not told, per file', '']
for rel, *_ in summary:
    un = [r[1] for r in rows if r[0] == rel and r[2] == 'no']
    lines.append(f'- `{rel}` ({len(un)}): ' + ('; '.join(un) if un else 'none'))
(HERE / f'{name}.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
for s in summary: print(s[0], '| named', s[1], 'told', s[2], 'not', s[3], 'claims', s[4], '| updates', s[5])
